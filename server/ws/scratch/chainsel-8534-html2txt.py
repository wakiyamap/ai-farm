import re, sys, html
s = open(sys.argv[1], encoding='utf-8', errors='replace').read()
s = re.sub(r'<script.*?</script>', ' ', s, flags=re.S)
s = re.sub(r'<style.*?</style>', ' ', s, flags=re.S)
s = re.sub(r'</(tr|p|h\d|li|div)>', '\n', s)
s = re.sub(r'</t[dh]>', ' | ', s)
s = re.sub(r'<[^>]+>', '', s)
s = html.unescape(s)
s = re.sub(r'[ \t]+', ' ', s)
s = re.sub(r'\n\s*\n+', '\n', s)
open(sys.argv[2], 'w').write(s)
print(len(s))
